#!/usr/bin/env python
"""Write T-04, the 679-code label space by training frequency: codes, training and test observations per
bin (thesis Chapter 4).

The bins follow the two dashed lines in F-15: rare < 1,000, common 1,000–99,999, frequent >= 100,000
training occurrences. No code sits on a bin edge, so the edges are unambiguous. Observation counts are
those in the 679-code label space.

Reads data/labelspace/labelspace.csv (train_occ, test_occ, in_primary_ge10occ) and gates the counts.
Writes results/analysis/a1/tables/ch4_frequency_bins.tex (booktabs LaTeX) and the same table as an
image, results/analysis/a1/figures/ch4_frequency_bins_table.{png,pdf}, drawn at its natural width so it
prints 1:1 at 100%.

  python analysis/ch4_frequency_bins_table.py
"""
from __future__ import annotations
import importlib.util
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
_F = importlib.util.spec_from_file_location("figstyle", HERE / "lib" / "figstyle.py")
FS = importlib.util.module_from_spec(_F); _F.loader.exec_module(FS)
_B = importlib.util.spec_from_file_location("booktabs", HERE / "lib" / "booktabs.py")
BT = importlib.util.module_from_spec(_B); _B.loader.exec_module(BT)

LABELSPACE = HERE.parent / "data" / "labelspace" / "labelspace.csv"
FIG = HERE.parent / "results" / "analysis" / "a1" / "figures"
TAB = HERE.parent / "results" / "analysis" / "a1" / "tables"
EDGES = (1_000, 100_000)


def bins():
    d = pd.read_csv(LABELSPACE)
    p = d[d.in_primary_ge10occ == 1]
    lo, hi = EDGES
    masks = [("Rare", "<1,000", p.train_occ < lo),
             ("Common", "1,000–99,999", (p.train_occ >= lo) & (p.train_occ < hi)),
             ("Frequent", "≥100,000", p.train_occ >= hi)]
    rows = [(name, rng, int(m.sum()), int(p.train_occ[m].sum()), int(p.test_occ[m].sum())) for name, rng, m in masks]
    tot = ("Total", "", len(p), int(p.train_occ.sum()), int(p.test_occ.sum()))
    # gates: the expected counts, and the bins partition the space exactly
    assert [r[2] for r in rows] == [347, 261, 71] and tot[2] == 679
    assert [r[3] for r in rows] == [89_651, 4_337_054, 33_833_381] and tot[3] == 38_260_086
    assert [r[4] for r in rows] == [9_415, 433_521, 3_404_639] and tot[4] == 3_847_575
    assert not ((p.train_occ == lo) | (p.train_occ == hi)).any(), "a code sits on a bin edge"
    return rows, tot


def cells(rows, tot):
    """Body rows as strings: codes % to one decimal, observation % to two (the rare bin's share is
    a fraction of a percent)."""
    out = []
    for name, rng, n, tr, te in rows + [tot]:
        out.append([name, rng, f"{n:,}", f"{100 * n / tot[2]:.1f}", f"{tr:,}", f"{100 * tr / tot[3]:.2f}",
                    f"{te:,}", f"{100 * te / tot[4]:.2f}"])
    return out


GROUPS = [("LOINC codes", 2, 3), ("Training observations", 4, 5), ("Test observations", 6, 7)]
HEADER = ["Bin", "Training occurrences", "$n$", "%", "$n$", "%", "$n$", "%"]
RIGHT = {2, 3, 4, 5, 6, 7}  # numeric columns, right-aligned


def write_tex(body):
    TAB.mkdir(parents=True, exist_ok=True)
    out = TAB / "ch4_frequency_bins.tex"
    out.write_text(BT.tex(HEADER, body, groups=GROUPS, right=RIGHT, total=True,
                          caption=r"Share of train and test observations by rare vs.\ frequent LOINC codes",
                          label="tab:frequency-bins",
                          comment="T-04 -- generated by analysis/ch4_frequency_bins_table.py from data/labelspace/labelspace.csv"))
    return out


def draw(body):
    FIG.mkdir(parents=True, exist_ok=True)
    return BT.draw(FS, HEADER, body, str(FIG / "ch4_frequency_bins_table"), groups=GROUPS, right=RIGHT, total=True)


def build(write=True):
    rows, tot = bins()
    body = cells(rows, tot)
    for r in body:
        print("  " + " | ".join(r))
    if write:
        print("wrote", write_tex(body))
        png, w = draw(body)
        print(f"wrote {png} (natural width {w:.2f} in; text width {FS.TEXTWIDTH} in)")


if __name__ == "__main__":
    build()
