#!/usr/bin/env python
"""Write T-39, the train arm x test arm evaluation matrix (thesis Chapter 5). The table is conceptual and
reads no data.

The table is drawn here, without lib/booktabs.draw. The four cells carry a bold letter (A-D, the
names the text uses) and a description. At the text width, the description needs two lines for B and
C, and the second line is indented to start under the text after the letter. lib/booktabs has
single-line cells only. Instead of widening the shared layout for one conceptual table, this file
draws it with the same rule widths and spacing (imported from lib/booktabs). It writes the LaTeX with
a package-free nested tabular for the hanging indent.

Writes results/analysis/a1/tables/ch5_train_test_matrix.tex (booktabs LaTeX) and the same table as an
image, results/analysis/a1/figures/ch5_train_test_matrix_table.{png,pdf}.

  python analysis/ch5_train_test_matrix_table.py
"""
from __future__ import annotations
import importlib.util
from pathlib import Path
import matplotlib.pyplot as plt
from matplotlib.font_manager import FontProperties
from matplotlib.textpath import TextToPath

HERE = Path(__file__).resolve().parent
_F = importlib.util.spec_from_file_location("figstyle", HERE / "lib" / "figstyle.py")
FS = importlib.util.module_from_spec(_F); _F.loader.exec_module(FS)
_B = importlib.util.spec_from_file_location("booktabs", HERE / "lib" / "booktabs.py")
BT = importlib.util.module_from_spec(_B); _B.loader.exec_module(BT)

FIG = HERE.parent / "results" / "analysis" / "a1" / "figures"
TAB = HERE.parent / "results" / "analysis" / "a1" / "tables"
NAME = "ch5_train_test_matrix"

GROUP, ROWHEAD, COLS, ROWS = "Test arm", "Train arm", ["Clean", "Perturbed"], ["Clean", "Perturbed"]
#: (letter, description lines) per (train arm, test arm), line-broken for width
CELLS = {("Clean", "Clean"): ("A", ["The unperturbed baseline"]),
         ("Clean", "Perturbed"): ("B", ["The fragility of generalizing", "from a single site"]),
         ("Perturbed", "Clean"): ("C", ["Performance loss due to", "generalization"]),
         ("Perturbed", "Perturbed"): ("D", ["The robust model"])}
LINE = 1.2 * BT.SIZE       # line pitch inside a cell (LaTeX's 12 pt baselineskip at 10 pt)
HANG = 0.6 * BT.SIZE       # space between the bold letter and its description


def tex() -> str:
    def cell(letter, lines):
        body = r" \\ & ".join(lines)
        return rf"\begin{{tabular}}[t]{{@{{}}l@{{\hspace{{0.6em}}}}l@{{}}}}\textbf{{{letter}}} & {body}\end{{tabular}}"
    rows = [f"    {r} & " + " & ".join(cell(*CELLS[(r, c)]) for c in COLS) + r" \\" for r in ROWS]
    return "\n".join([
        "% T-39 -- generated by analysis/ch5_train_test_matrix_table.py",
        r"% needs \usepackage{booktabs}",
        r"\begin{table}[htbp]", r"  \centering",
        r"  \caption{The train arm $\times$ test arm evaluation matrix}", r"  \label{tab:train-test-matrix}",
        r"  \begin{tabular}{lll}", r"    \toprule",
        rf"     & \multicolumn{{2}}{{c}}{{{GROUP}}} \\", r"    \cmidrule(lr){2-3}",
        rf"    {ROWHEAD} & {COLS[0]} & {COLS[1]} \\", r"    \midrule",
        *rows, r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""])


def draw():
    FS.apply_paper(BT.SIZE)
    tp = TextToPath()
    def width(s, bold=False):
        return tp.get_text_width_height_descent(
            s, FontProperties(family="serif", size=BT.SIZE, weight="bold" if bold else "normal"), ismath=False)[0]
    letter_w = max(width(l, True) for l, _ in CELLS.values())
    col0 = max(width(s) for s in [ROWHEAD] + ROWS)
    cols = [max([width(c)] + [letter_w + HANG + width(t) for r in ROWS for t in CELLS[(r, c)][1]]) for c in COLS]
    natural = [col0] + cols
    span = cols[0] + cols[1] + 2 * BT.PAD                                   # the group header's columns
    short = width(GROUP) + 2 * BT.TRIM - span
    if short > 0:
        natural[1] += short / 2; natural[2] += short / 2
    left = [BT.PAD]
    for k in range(1, 3):
        left.append(left[-1] + natural[k - 1] + 2 * BT.PAD)
    W = left[-1] + natural[-1] + BT.PAD
    row_h = [BT.ROW + (max(len(CELLS[(r, c)][1]) for c in COLS) - 1) * LINE for r in ROWS]
    H = (BT.HEAVY + BT.BELOW + 2 * BT.ROW + sum(row_h) + 2 * (BT.ABOVE + BT.LIGHT + BT.BELOW)
         + BT.ABOVE + BT.HEAVY)
    fig = plt.figure(figsize=(W / 72, H / 72))
    ax = fig.add_axes([0, 0, 1, 1]); ax.set_axis_off(); ax.set_xlim(0, W); ax.set_ylim(0, H)

    def rule(y_top, lw, x0=0.0, x1=W):
        ax.plot([x0, x1], [y_top - lw / 2] * 2, color="black", lw=lw, solid_capstyle="butt")

    def text(x, y_line_top, s, bold=False, ha="left"):
        ax.text(x, y_line_top - BT.ROW + 0.3 * BT.ROW, s, ha=ha, va="baseline", fontsize=BT.SIZE,
                color="black", weight="bold" if bold else "normal")

    y = H
    rule(y, BT.HEAVY); y -= BT.HEAVY + BT.BELOW
    text((left[1] + left[2] + natural[2]) / 2, y, GROUP, ha="center")      # group header, centred
    y -= BT.ROW + BT.ABOVE
    rule(y, BT.LIGHT, left[1] - BT.PAD + BT.TRIM, left[2] + natural[2] + BT.PAD - BT.TRIM)   # \cmidrule(lr){2-3}
    y -= BT.LIGHT + BT.BELOW
    for k, h in enumerate([ROWHEAD] + COLS):
        text(left[k], y, h)
    y -= BT.ROW + BT.ABOVE; rule(y, BT.LIGHT); y -= BT.LIGHT + BT.BELOW
    for r, rh in zip(ROWS, row_h):
        text(left[0], y, r)
        for k, c in enumerate(COLS, start=1):
            letter, lines = CELLS[(r, c)]
            text(left[k], y, letter, bold=True)
            for j, t in enumerate(lines):
                text(left[k] + letter_w + HANG, y - j * LINE, t)
        y -= rh
    y -= BT.ABOVE; rule(y, BT.HEAVY); y -= BT.HEAVY
    assert abs(y) < 1e-6, y
    return FS.save(fig, str(FIG / f"{NAME}_table")), W / 72


def build(write=True):
    for r in ROWS:
        print("  " + r + " | " + " | ".join(f"{l} {' / '.join(t)}" for l, t in (CELLS[(r, c)] for c in COLS)))
    if write:
        TAB.mkdir(parents=True, exist_ok=True); FIG.mkdir(parents=True, exist_ok=True)
        (TAB / f"{NAME}.tex").write_text(tex())
        print("wrote", TAB / f"{NAME}.tex")
        png, w = draw()
        print(f"wrote {png} (natural width {w:.2f} in; text width {FS.TEXTWIDTH} in)")


if __name__ == "__main__":
    build()
