#!/usr/bin/env python
"""Write T-01, the patient split counts: from MIMIC-IV to the train, validation and test splits (thesis
Chapter 4).

The table is the patient flow behind every experiment: who is eligible, who is removed because
FHIR-MLM was pretrained on them, and how the remaining clean pool is split. The splits partition the
clean pool, so they are drawn as indented sub-rows of it.

The exclusion row is 68,010, although FHIR-MLM's stage-2 pretraining corpus had 68,989 patients
(`counts.pretrain`). Only the patients who are also eligible are removed. The clean pool is the
eligible patients minus their intersection with the pretraining corpus (pipeline/01_build_split.py).
Some pretraining patients were never eligible, so 250,486 − 68,989 does not give the clean pool, but
250,486 − 68,010 = 182,476 does. The script takes the exclusion as eligible minus clean pool, and the
gates check these counts.

Reads data/splits/manifest.json (`counts`, `overlaps`) and the row count of the patient summary the
split was built from. Writes aggregate counts only: results/analysis/a1/tables/ch4_patient_splits.tex
(booktabs LaTeX) and the same table as an image,
results/analysis/a1/figures/ch4_patient_splits_table.{png,pdf}.

  python analysis/ch4_patient_splits_table.py
"""
from __future__ import annotations
import csv
import importlib.util
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))
import locations  # noqa: E402

HERE = Path(__file__).resolve().parent
_F = importlib.util.spec_from_file_location("figstyle", HERE / "lib" / "figstyle.py")
FS = importlib.util.module_from_spec(_F); _F.loader.exec_module(FS)
_B = importlib.util.spec_from_file_location("booktabs", HERE / "lib" / "booktabs.py")
BT = importlib.util.module_from_spec(_B); _B.loader.exec_module(BT)

MANIFEST = HERE.parent / "data" / "splits" / "manifest.json"
SUMMARY = locations.UPSTREAM / "loinc_patients_summary.csv"   # 01_build_split.SUMMARY_FILE
FIG = HERE.parent / "results" / "analysis" / "a1" / "figures"
TAB = HERE.parent / "results" / "analysis" / "a1" / "tables"
HEADER = ["Set", "Patients"]
RIGHT = {1}


def counts():
    m = json.loads(MANIFEST.read_text())
    c = m["counts"]
    with open(SUMMARY, newline="") as f:
        n_mimic = sum(1 for _ in csv.reader(f)) - 1                     # minus the header row
    excluded = c["eligible"] - c["clean_pool"]
    # gates: the manifest's arithmetic, the measured intersection, the partition, no overlaps
    assert n_mimic == 299_712 and c["eligible"] == 250_486 and c["clean_pool"] == 182_476
    assert excluded == 68_010 and c["pretrain"] == 68_989 and excluded <= c["pretrain"]
    assert c["train"] + c["val"] + c["test"] + c["reserve_pool"] == c["clean_pool"]
    assert (c["train"], c["val"], c["test"], c["reserve_pool"]) == (100_000, 2_000, 10_000, 70_476)
    assert all(v == 0 for v in m["overlaps"].values()), m["overlaps"]
    return n_mimic, excluded, c


def build(write=True):
    n_mimic, excluded, c = counts()
    body = [["MIMIC-IV patients", f"{n_mimic:,}"],
            ["Eligible", f"{c['eligible']:,}"],
            ["FHIR-MLM stage-2 pretraining (excluded)", f"{excluded:,}"],
            ["Clean pool", f"{c['clean_pool']:,}"],
            ["Train", f"{c['train']:,}"],
            ["Validation", f"{c['val']:,}"],
            ["Test", f"{c['test']:,}"],
            ["Reserve (unused)", f"{c['reserve_pool']:,}"]]
    indent = {4, 5, 6, 7}                                                # the splits partition the clean pool
    for i, r in enumerate(body):
        print(("    " if i in indent else "  ") + " | ".join(r))
    if write:
        TAB.mkdir(parents=True, exist_ok=True); FIG.mkdir(parents=True, exist_ok=True)
        tex = TAB / "ch4_patient_splits.tex"
        tex.write_text(BT.tex(HEADER, body, right=RIGHT, total=False, indent=indent,
                              caption="Patient split counts", label="tab:patient-splits",
                              comment="T-01 -- generated by analysis/ch4_patient_splits_table.py "
                                      "from data/splits/manifest.json"))
        print("wrote", tex)
        png, w = BT.draw(FS, HEADER, body, str(FIG / "ch4_patient_splits_table"), right=RIGHT, total=False,
                         indent=indent)
        print(f"wrote {png} (natural width {w:.2f} in; text width {FS.TEXTWIDTH} in)")


if __name__ == "__main__":
    build()
