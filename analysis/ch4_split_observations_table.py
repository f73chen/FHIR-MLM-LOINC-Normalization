#!/usr/bin/env python
"""Write the table of patients and lab observations per split (thesis Chapter 4).

The observations counted are the lab observations whose LOINC code is in the 679-code label space,
over every patient in the split. This is what pipeline/06_tfidf_dataset.py writes into the TF-IDF
datasets, and what TF-IDF trains and is scored on. The deep models see the subset inside their
8,192-token windows.

Data (aggregate counts only):
    patients      data/splits/manifest.json `counts`
    observations  train / test: train_obs / test_obs in the v3 TF-IDF dataset manifests (the counts
                  from 06), for both arms. The arms must agree, because perturbation changes only
                  the numbers.
                  val (no manifest entry): counted line by line from the val labels, both arms.
                  The gated train and test counts agree with two independent checks. The loader in
                  07 reads 38,260,086 train observations from the sample files, and every TF-IDF
                  test dump has 3,847,575 rows.

Writes results/analysis/a1/tables/ch4_split_observations.tex (booktabs LaTeX) and the same table as an
image, results/analysis/a1/figures/ch4_split_observations_table.{png,pdf}.

  python analysis/ch4_split_observations_table.py
"""
from __future__ import annotations
import importlib.util
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))
import locations  # noqa: E402

HERE = Path(__file__).resolve().parent
_F = importlib.util.spec_from_file_location("figstyle", HERE / "lib" / "figstyle.py")
FS = importlib.util.module_from_spec(_F); _F.loader.exec_module(FS)
_B = importlib.util.spec_from_file_location("booktabs", HERE / "lib" / "booktabs.py")
BT = importlib.util.module_from_spec(_B); _B.loader.exec_module(BT)

SPLITS = HERE.parent / "data" / "splits" / "manifest.json"
DATASETS = locations.WORK / "tfidf"
FIG = HERE.parent / "results" / "analysis" / "a1" / "figures"
TAB = HERE.parent / "results" / "analysis" / "a1" / "tables"
HEADER = ["Split", "Patients", "Lab observations"]
RIGHT = {1, 2}
ROWS = [("Train", "train"), ("Validation", "val"), ("Test", "test")]


def count_labels(split_dir: Path) -> tuple[int, int]:
    """(patient files, observation lines) in the labels folder of one split."""
    n_files = n_obs = 0
    with os.scandir(split_dir / "labels") as it:
        for e in it:
            if e.name.endswith(".txt"):
                n_files += 1
                with open(e.path) as f:
                    n_obs += sum(1 for line in f if line.strip())
    return n_files, n_obs


def counts():
    patients = json.loads(SPLITS.read_text())["counts"]
    obs = {}
    for arm in ("clean", "pert"):
        d = DATASETS / f"dataset_v3__{arm}"
        man = json.loads((d / "manifest.json").read_text())
        assert man["label_space"] == 679
        for _, split in ROWS:
            if split == "val":                                              # no manifest entry: count it
                n_files, n_obs = count_labels(d / split)
                assert n_files == patients[split], (arm, split, n_files)    # one labels file per patient
            else:
                n_obs = man[f"{split}_obs"]
            obs.setdefault(split, set()).add(n_obs)
    assert all(len(v) == 1 for v in obs.values()), f"the arms disagree: {obs}"
    obs = {k: v.pop() for k, v in obs.items()}
    assert (obs["train"], obs["val"], obs["test"]) == (38_260_086, 793_834, 3_847_575)
    return patients, obs


def build(write=True):
    patients, obs = counts()
    body = [[name, f"{patients[k]:,}", f"{obs[k]:,}"] for name, k in ROWS]
    for r in body:
        print("  " + " | ".join(r))
    if write:
        TAB.mkdir(parents=True, exist_ok=True); FIG.mkdir(parents=True, exist_ok=True)
        tex = TAB / "ch4_split_observations.tex"
        tex.write_text(BT.tex(HEADER, body, right=RIGHT, total=False,
                              caption="Patients and lab observations per split", label="tab:split-observations",
                              comment="generated by analysis/ch4_split_observations_table.py from "
                                      "data/splits/manifest.json and the v3 TF-IDF datasets"))
        print("wrote", tex)
        png, w = BT.draw(FS, HEADER, body, str(FIG / "ch4_split_observations_table"), right=RIGHT, total=False)
        print(f"wrote {png} (natural width {w:.2f} in; text width {FS.TEXTWIDTH} in)")


if __name__ == "__main__":
    build()
