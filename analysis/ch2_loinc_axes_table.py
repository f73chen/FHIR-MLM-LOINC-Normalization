#!/usr/bin/env python
"""Write T-40 as a LaTeX table: the six axes of one LOINC code, and two codes that each differ from it on
one axis (thesis Chapter 2).

The axis on which a code differs from 2951-2 (Sodium SerPl-sCnc) is bold on a light grey cell. The
script checks that the three codes are in the label space, that each of the other two differs from
2951-2 on exactly one axis, and that they differ on different axes.

The table has no name column. The LOINC licence (section 10.3) wants a code shown with one of its
official names, and the six axis columns are the code's fully specified name, one of the four it
accepts. A column of long common names would make the table wider than the text.

Reads LoincTableCore.csv (LOINC 2.82) from UPSTREAM_DIR and data/labelspace/labelspace.csv. Writes
results/analysis/ch2/tables/ch2_loinc_axes.tex (booktabs, needs colortbl).

  python analysis/ch2_loinc_axes_table.py
"""
from __future__ import annotations
import importlib.util
from pathlib import Path
import sys
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))
import locations  # noqa: E402

HERE = Path(__file__).resolve().parent
_B = importlib.util.spec_from_file_location("booktabs", HERE / "lib" / "booktabs.py")
BT = importlib.util.module_from_spec(_B); _B.loader.exec_module(BT)
TAB = HERE.parent / "results" / "analysis" / "ch2" / "tables"
LOINC = locations.UPSTREAM / "Loinc_2.82/LoincTableCore/LoincTableCore.csv"
LABELSPACE = HERE.parent / "data" / "labelspace" / "labelspace.csv"

AXES = ["COMPONENT", "PROPERTY", "TIME_ASPCT", "SYSTEM", "SCALE_TYP", "METHOD_TYP"]
HEADER = ["LOINC", "Component", "Property", "Time", "System", "Scale", "Method"]
# 2951-2 Sodium SerPl-sCnc; 2947-0 Sodium Bld-sCnc; 2075-0 Chloride SerPl-sCnc
CODES = ["2951-2", "2947-0", "2075-0"]
SHADE = r"\cellcolor[gray]{0.88}"     # light grey, #e0e0e0


def build(write=True):
    d = pd.read_csv(LOINC, low_memory=False, usecols=["LOINC_NUM"] + AXES).set_index("LOINC_NUM")
    rows = d.loc[CODES]
    prim = set(pd.read_csv(LABELSPACE).query("in_primary_ge10occ == 1").loinc)
    assert all(c in prim for c in CODES)
    base = rows.loc["2951-2"]
    differs_on = {c: [a for a in AXES if str(rows.loc[c, a]) != str(base[a])] for c in CODES[1:]}
    assert all(len(v) == 1 for v in differs_on.values()), differs_on              # each differs on exactly one axis
    assert differs_on["2947-0"] != differs_on["2075-0"], differs_on              # ... on different axes

    body = []
    for c in CODES:
        parts = []
        for a in AXES:
            v = "–" if pd.isna(rows.loc[c, a]) else str(rows.loc[c, a])
            parts.append(rf"{SHADE}\textbf{{{v}}}" if a in differs_on.get(c, []) else v)
        body.append([c] + parts)
    tex = BT.tex(HEADER, body, total=False, caption="Three LOINC codes and their six axes", label="tab:loinc-axes",
                 comment="T-40 -- generated by analysis/ch2_loinc_axes_table.py from LOINC 2.82")
    tex = tex.replace(r"% needs \usepackage{booktabs}", r"% needs \usepackage{booktabs}, \usepackage{colortbl}", 1)
    if write:
        TAB.mkdir(parents=True, exist_ok=True)
        (TAB / "ch2_loinc_axes.tex").write_text(tex, encoding="utf-8")
        print("wrote", TAB / "ch2_loinc_axes.tex")
    return tex


if __name__ == "__main__":
    print(build())
